const char *muse_tr(const char *english)
{
    if (!muse_settings_chinese()) return english;
    for (unsigned i = 0; i < sizeof(translations) / sizeof(translations[0]); i++) {
        if (strcmp(english, translations[i].en) == 0) return translations[i].zh;
    }
    return english;
}
